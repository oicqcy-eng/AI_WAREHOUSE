

SELECT
	OMB.MONO ,/*工單編號*/
	baselotno as 'LOTNO'
   ,CASE OMB.MOSTATE
		WHEN 0 THEN N'0:未確認'
		WHEN 1 THEN N'1:簽核中'
		WHEN 2 THEN N'2:已確認'
		WHEN 3 THEN N'3:已下線'
		WHEN 6 THEN N'6:線邊倉'
		WHEN 99 THEN N'99:工單結案'
	END
	MOSTATE /*工單狀態*/
   ,OMB.PRODUCTNO /*產品編號*/
   ,PRD.PRODUCTNAME /*產品名稱*/
   ,OMB.MOQTY /*工單數量*/
   ,OMB.UNRELEASELOTQTY /*未下線數量*/
   ,ROUND(ISNULL(WLS.CURQTY, 0) / OMB.MOQTY *100, 2) AS COMPLETE_RATE /*工單完成率*/
   ,ISNULL(WLS.CURQTY, 0) AS COMPLETE_QTY /*工單完成數量*/
   ,ROUND ((ISNULL (WLS.CURQTY, 0) + ISNULL (FAIL.FAILQTY, 0))/ OMB.MOQTY * 100,2) AS COMPLETEWORK_RATE /*工單完工率*/
   ,ISNULL (WLS.CURQTY, 0) + ISNULL (FAIL.FAILQTY, 0) AS COMPLETEWORK_QTY /*工單完工數量*/
   ,CONVERT(CHAR(10), FAIL.INPUTDATE, 20) OLD_INPUTDATE /*最早輸入日期*/
   ,CONVERT(CHAR(10), OMB.PLANFINISHDATE, 20) PLANFINISHDATE /*預計完成日*/
   ,ISNULL(WLS.CURQTY, 0) AS GOODQTY /*良品數 mantis 55506 modi*/
   ,ISNULL(FAIL.FAILQTY, 0) AS FAILQTY /*不良品數*/
   ,OMB.MOUNITNO /*單位*/
   ,OMB.DESCRIPTION AS MO_DESCRIPTION/*工單說明*/
   ,CUS.CUSTOMERNAME /*客戶名稱*/
   ,OMB.RONO /*訂單編號*/
	/*,OMB.ITEMNO 訂單序號*/
   ,OMB.CREATOR /*建立者*/
   ,OMB.CUSTOMERNO /*客戶編號*/
   ,OMB.PRODUCTVERSION /*產品版本*/
   ,CONVERT(CHAR(10), ISNULL(TD.ORDERDate,RO.DUEDATE), 20) DueDate /*#82662修改來源#93917再次修改*//*訂單預交日*/
   ,PRD.ItemSpec /*規格*/
   ,CONVERT(CHAR(10), OMB.PlanStartDate, 20) PlanStartDate /*預計開工時間*/
FROM TBLOEMOBASIS OMB
INNER JOIN TBLPRDPRODUCTBASIS PRD
	ON OMB.PRODUCTNO = PRD.PRODUCTNO AND OMB.PRODUCTVERSION = PRD.PRODUCTVERSION
LEFT JOIN TBLENTCUSTOMERBASIS CUS
	ON OMB.CUSTOMERNO = CUS.CUSTOMERNO
LEFT JOIN TBLOEROBASIS RO
	ON OMB.RONO = RO.RONO
LEFT JOIN TBLOERODETAIL TD ON OMB.RONO = TD.RONO  /*#82662修改來源*/
        AND OMB.PRODUCTNO = TD.PRODUCTNO
		AND OMB.ITEMNO=TD.ITEMNO   /*#91086*/
LEFT JOIN (SELECT
		A.BASELOTNO,
		A.PRODUCTNO
	   ,A.PRODUCTVERSION
	   ,B.MONO
	   ,SUM(B.GOODQTY) AS GOODQTY
	   ,SUM(B.FAILQTY) AS FAILQTY
	   ,MIN(A.CREATEDATE) AS INPUTDATE
	FROM TBLWIPLOTBASIS A
		,TBLWIPLOTLOG_REPORT B
	WHERE A.BASELOTNO = B.BASELOTNO
	AND B.STATUS = 1
	GROUP BY 
			A.BASELOTNO,
			A.PRODUCTNO
			,A.PRODUCTVERSION
			,B.MONO) FAIL
	ON OMB.MONO = FAIL.MONO
LEFT JOIN (SELECT
		B.MONO
	   ,SUM(A.CURQTY) CURQTY
	FROM TBLWIPLOTSTATE A
	JOIN TBLWIPLOTBASIS B
		ON A.BASELOTNO = B.BASELOTNO
	WHERE STATUS = 11
	OR A.STATUS = 99
	GROUP BY B.MONO) WLS
	ON OMB.MONO = WLS.MONO

