SELECT
    CASE WHEN EXISTS (
        SELECT 1
        FROM TBLPRDPRODUCTPROCESS PP
        JOIN TBLPRSNODEBASIS NB ON PP.PROCESSNO = NB.PROCESSNO
        WHERE PP.PRODUCTNO = OMB.PRODUCTNO
        AND NB.NODENO IN ('LCX01','LCX02','CX03','RCX03','CX02')
    ) THEN N'是' ELSE N'否' END AS 工单是否数采 /*是否数采*/
   ,OMB.MONO /*工单编号*/
   ,CASE OMB.MOSTATE
		WHEN 0 THEN N'0:未确认'
		WHEN 1 THEN N'1:签核中'
		WHEN 2 THEN N'2:已确认'
		WHEN 3 THEN N'3:已下线'
		WHEN 6 THEN N'6:线边仓'
		WHEN 99 THEN N'99:工单结案'
	END MOSTATE /*工单状态*/
   ,OMB.RONO /*订单编号*/
   ,OMB.PRODUCTNO /*产品编号*/
   ,PRD.PRODUCTNAME /*产品名称*/
   ,PRD.GraphNo
   ,PRD.ItemSpec /*规格*/
   ,OMB.DESCRIPTION MODESCRIPTION /*工单说明*/
   ,OMB.MOQTY /*工单数量*/
   ,OMB.UNRELEASELOTQTY /*未下线数量*/
   ,ROUND(ISNULL(WLS.CURQTY, 0) / OMB.MOQTY *100, 2) AS COMPLETE_RATE /*工单完成率*/
   ,ISNULL(WLS.CURQTY, 0) AS COMPLETE_QTY /*完成数量*/
   ,ROUND((ISNULL(WLS.CURQTY, 0)+ISNULL(FAIL.FAILQTY, 0)) / OMB.MOQTY *100, 2) AS COMPLETEWORK_RATE /*工单完工率*/
   ,ISNULL(WLS.CURQTY, 0)+ISNULL(FAIL.FAILQTY, 0) AS COMPLETEWORK_QTY /*完工数量*/
   ,CONVERT(CHAR(10), FAIL.INPUTDATE, 20) INPUTDATE /*下线日*/
   ,CONVERT(CHAR(10), OMB.PLANFINISHDATE, 20) PLANFINISHDATE /*预计完成日*/
   ,ISNULL(WLS.CURQTY, 0) AS GOODQTY /*良品数 mantis 55506 modi*/
   ,ISNULL(FAIL.FAILQTY, 0) AS FAILQTY /*不良品数*/
   ,OMB.MOUNITNO /*单位*/  
   ,CUS.CUSTOMERNAME /*客户名称*/
   ,OMB.CREATOR /*建立者*/
   ,OMB.CUSTOMERNO /*客户编号*/
   ,OMB.PRODUCTVERSION /*产品版本*/
   ,CONVERT(CHAR(10), RO.DueDate, 20) DueDate /*订单预交日#93917调整*/
   ,CONVERT(CHAR(10), OMB.PlanStartDate, 20) PlanStartDate /*预计开工时间*/
FROM TBLOEMOBASIS OMB
JOIN TBLPRDPRODUCTBASIS PRD ON OMB.PRODUCTNO = PRD.PRODUCTNO AND OMB.PRODUCTVERSION = PRD.PRODUCTVERSION 
LEFT JOIN TBLENTCUSTOMERBASIS CUS ON OMB.CUSTOMERNO = CUS.CUSTOMERNO
/*#93917修改订单交期来源 start*/
LEFT JOIN (
    SELECT RL.RONO, RL.ITEMNO, ISNULL(RL.ORDERDATE, RB.DUEDATE) DUEDATE
    FROM TBLOERODETAIL RL, TBLOEROBASIS RB
    WHERE RL.RONO = RB.RONO
) RO ON RO.RONO = OMB.RONO AND RO.ITEMNO = OMB.ITEMNO
/*#93917修改订单交期来源 end*/
LEFT JOIN (
    SELECT
        A.PRODUCTNO
       ,A.PRODUCTVERSION
       ,B.MONO
       ,SUM(B.GOODQTY) AS GOODQTY
       ,SUM(B.FAILQTY) AS FAILQTY
       ,MIN(A.CREATEDATE) AS INPUTDATE
    FROM TBLWIPLOTBASIS A
        ,TBLWIPLOTLOG_REPORT B
    WHERE A.BASELOTNO = B.BASELOTNO
    GROUP BY A.PRODUCTNO
            ,A.PRODUCTVERSION
            ,B.MONO
) FAIL ON OMB.MONO = FAIL.MONO
LEFT JOIN (
    SELECT B.MONO, SUM(A.CURQTY) CURQTY
    FROM TBLWIPLOTSTATE A
    JOIN TBLWIPLOTBASIS B ON A.BASELOTNO = B.BASELOTNO
    WHERE STATUS = 11 OR A.STATUS = 99
    GROUP BY B.MONO
) WLS ON OMB.MONO = WLS.MONO