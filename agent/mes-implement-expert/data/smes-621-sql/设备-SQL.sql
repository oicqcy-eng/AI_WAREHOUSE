
/*设备*/

SELECT c.EQUIPMENTTYPE  /*設備類別*/
      ,c.EQUIPMENTNO    /*設備編號*/
      ,c.EquipmentName  /*設備名稱*/
      ,CONVERT(CHAR(16),a.EVENTTIME,120) EVENT_TIME /*事件時間*/
      ,ROUND(SUM(a.RESVALUE)/60,2) REALMACHINETIME_H /*工時(時)*/
      ,SUM(a.INPUTQTY) INPUTQTY /*數量*/
	  ,a.LOTNO
	  ,a.OPNO  /*#117127，子表增加KEY*/
FROM tblWIPCont_Resource a
JOIN TBLEQPEQUIPMENTBASIS c ON a.RESITEM=c.EQUIPMENTNO
WHERE EXISTS (
  SELECT *
  FROM V_Q05
  WHERE V_Q05.LOTNO=a.LOTNO AND V_Q05.OPNO=a.OPNO
/*{{a.LOTNO}}*/
/*{{a.OPNO}}*/
/*{{V_Q05.STARTTIME}}*/
/*{{V_Q05.STARTTIME}}*/
/*{{V_Q05.PRODUCTNO}}*/
/*{{V_Q05.PRODUCTNAME}}*/
/*{{V_Q05.CUSTOMERNO}}*/
/*{{V_Q05.CUSTOMERNAME}}*/
/*{{V_Q05.RONO}}*/
/*{{V_Q05.MONO}}*/
/*{{V_Q05.DTYPENAME}}*/
) AND a.RESCLASS=1
GROUP BY c.EQUIPMENTTYPE,c.EQUIPMENTNO,c.EquipmentName,CONVERT(CHAR(16),a.EVENTTIME,120),a.LOTNO,a.OPNO /*#117127，子表增加KEY*/
ORDER BY CONVERT(CHAR(16),A.EVENTTIME,120), C.EQUIPMENTNO