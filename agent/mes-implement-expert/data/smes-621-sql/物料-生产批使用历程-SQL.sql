select B.OPNO,D.OPNAME,B.LOTNO,A.MATERIALTYPE RT601_MATERIALTYPE,A.MATERIALNO,A.USEQTY,A.UNITNO,C.MATERIALLOTNO,C.LOTQTY,C.EQUIPMENTNO,A.DESCRIPTION from  TBLWIPCONT_MATERIAL  A 
left join TBLWIPCONT_MATERIALLOT  C on A.LOGGROUPSERIAL=C.LOGGROUPSERIAL and A.MATERIALNO=C.MATERIALNO 
left join TBLWIPLOTLOG_REPORT  B on A.LOGGROUPSERIAL=B.LOGGROUPSERIAL 
left join TBLOPBASIS D on B.OPNO = D.OPNO